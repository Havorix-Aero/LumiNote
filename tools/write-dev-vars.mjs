import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes `packages/worker/.dev.vars` with fresh local-only secrets.
 *
 * Local development and the end-to-end suite both need `SESSION_PEPPER` and `TOTP_MASTER_KEY`;
 * generating them in one place avoids hand-editing and keeps CI shell-agnostic.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'packages/worker/.dev.vars');

if (existsSync(target) && !process.argv.includes('--force')) {
  console.warn(`${target} already exists. Re-run with --force to overwrite it.`);
  process.exit(0);
}

const secret = () => randomBytes(32).toString('base64url');

const contents = [
  '# Generated by tools/write-dev-vars.mjs. Local development only - never commit this file.',
  `SESSION_PEPPER="${secret()}"`,
  `TOTP_MASTER_KEY="${secret()}"`,
  '# wrangler.toml carries the deployed values, so local development overrides ENVIRONMENT here.',
  'ENVIRONMENT="development"',
  'LLM_PROVIDER="mock"',
  'LLM_BASE_URL="https://api.deepseek.com/v1"',
  'LLM_MODEL="deepseek-chat"',
  'STT_PROVIDER="mock"',
  '',
].join('\n');

writeFileSync(target, contents, 'utf8');
console.log(`Wrote ${target}`);
